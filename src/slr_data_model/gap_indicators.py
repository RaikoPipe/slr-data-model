from typing import Optional

from pydantic import BaseModel, Field, model_validator

from .annotation_helper import make_type_annotations, reasoning_field
from .common import UniqueList, require_iff, require_spec_iff
from .descriptive_enum import DescriptiveEnum


class HITLType(DescriptiveEnum):
    """Types of human-in-the-loop patterns per §3.8."""
    APPROVAL_GATE = "approval-gate", (
        "Workflow-initiated: a human must check the output and actively correct it when wrong before the workflow "
        "proceeds; mere acknowledgement or display does not count (D086)"
    )
    WHAT_IF_INTERFACE = "what-if-interface", "Human-initiated: human poses scenarios or changes inputs to explore outcomes"
    ESCALATION_PROTOCOL = "escalation-protocol", (
        "System-initiated: the system detects uncertainty, failure or missing information and asks the human"
    )
    ITERATIVE_FEEDBACK = "iterative-feedback", (
        "Human judges each iteration's output and gives guidance that steers the next iteration"
    )
    HUMAN_OVERRIDE = "human-override", "Human edits or vetoes the agents' intermediate decisions or plans"
    OTHER = "other", "Other HITL pattern (specify)"


class DomainKnowledgeType(DescriptiveEnum):
    """Types of domain knowledge formalization per §3.8.

    v0.9.0 (B8): descriptions sharpened so that ontology (T-box: classes, relations, axioms), knowledge graph
    (A-box: instance data in a graph) and structured schema (non-graph schema) no longer overlap; following
    Hogan et al. (2021), "Knowledge Graphs", ACM Computing Surveys 54(4). Both ontology and knowledge-graph may
    be coded for an ontology-backed KG; either triggers the kg_* detail fields.
    """
    ONTOLOGY = "ontology", "Formal ontology: classes, relations and axioms of the domain (e.g., OWL), schema level"
    KNOWLEDGE_GRAPH = "knowledge-graph", "Knowledge graph: domain instances and their relations stored as a graph"
    STANDARDS_ENCODING = "standards-encoding", (
        "Machine-readable encoding of domain standards (e.g., VDI 5200, ISA-95, ISO 22400, Asset Administration Shell "
        "and other Industry 4.0 metamodels); also coded as ontology only if the paper presents or uses the standard as an "
        "ontology or semantic model, a standard used as an XML/JSON schema alone is structured-schema (0.10.5)"
    )
    STRUCTURED_SCHEMA = "structured-schema", (
        "Non-graph metamodel or schema (e.g., JSON Schema, UML) for domain entities and constraints; includes predefined "
        "input/output schemas for domain entities that LLM output must conform to and XML/JSON serialisations of domain "
        "models (0.10.5)"
    )
    RELATIONAL_DATABASE = "relational-database", (
        "Relational database or taxonomy of domain entities and attributes; external datasets that only serve as input "
        "data for the analysis do not count (0.10.5)"
    )
    CODE_TEMPLATE = "code-template", (
        "Code or model template encoding domain structure (e.g., simulation blueprint); includes existing domain code the "
        "LLM receives as content to adapt or extend, such as solver model code; tools or functions the LLM only calls "
        "do not count (0.10.5)"
    )
    MATHEMATICAL_MODEL = "mathematical-model", (
        "Optimization or simulation model of the planning domain encoding its structure and rules, specified (variables, "
        "constraints or simulation logic) and used by the system; loss functions, training objectives, ML/statistical "
        "predictors, scoring or index formulas and generic objective sketches do not count (0.10.5)"
    )
    OTHER = "other", "Other domain knowledge formalization (specify)"


KG_TYPES = frozenset({DomainKnowledgeType.ONTOLOGY, DomainKnowledgeType.KNOWLEDGE_GRAPH})


class KGModel(DescriptiveEnum):
    """Graph data model of the ontology/KG (B8). Source: Hogan et al. (2021), ACM Computing Surveys 54(4), §2;
    RDF 1.1 and OWL 2 (W3C Recommendations); property graphs per Angles (2018), "The Property Graph Database
    Model", AMW 2018."""
    RDF_OWL = "RDF-OWL", "RDF triples, optionally with RDFS/OWL semantics (triple store, SPARQL)"
    LABELED_PROPERTY_GRAPH = "labeled-property-graph", "Labelled property graph (e.g., Neo4j, Cypher)"
    OTHER = "other", "Other graph representation (e.g., in-memory graph, JSON adjacency); describe in domain_knowledge_description"
    NR = "NR", "Graph model not reported"


class KGConstruction(DescriptiveEnum):
    """How the ontology/KG was built (B8)."""
    MANUAL = "manual", "Modelled by hand by experts or the authors"
    LLM_EXTRACTED = "LLM-extracted", "Populated or generated by an LLM from documents or data"
    HYBRID = "hybrid", "LLM extraction with human curation, or manual core extended by LLM"
    REUSED = "reused", "Existing ontology/KG reused (possibly extended)"
    NR = "NR", "Construction not reported"


class KGUsage(DescriptiveEnum):
    """What the system does with the ontology/KG at run time (B8). GraphRAG per Edge et al. (2024), "From Local to
    Global: A Graph RAG Approach to Query-Focused Summarization", arXiv:2404.16130."""
    RETRIEVAL = "retrieval", "Retrieval of context for the LLM (GraphRAG, SPARQL/Cypher lookup)"
    CONSTRAINT_CHECKING = "constraint-checking", "Checking LLM output for consistency with constraints/rules (e.g., SHACL)"
    REASONING_INFERENCE = "reasoning-inference", "Logical reasoning or inference over the graph"
    PLANNING_STATE = "planning-state", "Graph holds and is updated with the evolving plan/system state"


class AutomationStage(DescriptiveEnum):
    """Information-processing stage(s) the system automates (B7).

    Source: Parasuraman, Sheridan & Wickens (2000), "A model for types and levels of human interaction with
    automation", IEEE Trans. Systems, Man, and Cybernetics A 30(3). The first three map onto Simon's (1960,
    The New Science of Management Decision) intelligence, design and choice phases.
    """
    INFORMATION_ACQUISITION = "information-acquisition", (
        "System gathers or filters input from sources beyond the given problem instance at run time (retrieval over "
        "documents/databases, web/API search, sensor or ERP queries, archives of past runs) (intelligence). Encoding the "
        "given instance for the LLM (serialising, summary statistics, rendered images) and deterministic pre-processing "
        "of the supplied input data do not count (0.10.4)"
    )
    INFORMATION_ANALYSIS = "information-analysis", "Integrating, interpreting, predicting; generating alternatives (intelligence/design)"
    DECISION_SELECTION = "decision-selection", (
        "System actively evaluates and ranks alternatives, recommending or choosing one final option (choice); "
        "generating alternatives for the human to rank does not count (D092), nor does handing the human a set of "
        "non-dominated alternatives (Pareto front) or selection inside the search (0.10.4)"
    )
    ACTION_IMPLEMENTATION = "action-implementation", (
        "System writes the selected decision into a plan, model or system (e.g., a tool call updating the layout, code "
        "edits to the simulation model, triggering actions) and carries it out itself; counts even if not deployed in "
        "real production. Returning or reporting the selected solution, or a human triggering the action (e.g., a "
        "dashboard button), does not count (0.10.4)"
    )


class DecisionAutonomy(DescriptiveEnum):
    """Ordinal level of decision autonomy (B7), condensed from the 10-level scale of Sheridan & Verplank (1978) as
    used by Parasuraman, Sheridan & Wickens (2000)."""
    L1_OPTIONS = "1-options", "System lists or generates options; human evaluates and decides"
    L2_RECOMMENDATION = "2-recommendation", "System recommends one option; human decides"
    L3_VETO = "3-veto", "System decides and implements unless the human vetoes"
    L4_AUTONOMOUS = "4-autonomous", "System decides and implements without human approval"


class EvaluationFrameworkType(DescriptiveEnum):
    """Types of evaluation frameworks per §3.8."""
    BENCHMARK = "benchmark", "Public, standardised benchmark reused from prior work"
    CUSTOM_TEST_SET = "custom-test-set", "Test items or cases built by the authors for this paper"
    EXPERT_GROUND_TRUTH = "expert-ground-truth", "Outputs compared with expert or practitioner decisions"
    RUBRIC = "rubric", (
        "Explicit graded scoring scale (incl. Likert ratings, ordinal suitability levels); comparing outcome "
        "categories (e.g., correct/incorrect, match/mismatch) is not enough (D052)"
    )
    DOMAIN_SPECIFIC_METRIC = "domain-specific-metric", (
        "Metric defined by the planning domain (e.g., throughput, space utilisation, cost); not generic accuracy/F1"
    )
    OTHER = "other", "Other evaluation framework (specify)"


class GapIndicators(BaseModel):
    """Gap indicator fields (LLM; interpretive; R1 + R2 verify 100%)."""
    hitl_pattern_present: bool = Field(
        description="True if a human acts on intermediate or final LLM output inside the method's workflow "
        "(reviews, approves, edits, answers a system request, steers exploration). Only issuing the initial "
        "query or reading the final answer does not count."
    )
    hitl_pattern_present_reasoning: str = reasoning_field(interpretive=True)
    hitl_type: Optional[UniqueList[HITLType]] = Field(
        default=None,
        description="All HITL patterns present, required if hitl_pattern_present is true. Classify by who "
        "triggers the human step (workflow, human, system) and when." + make_type_annotations(HITLType)
    )
    hitl_type_reasoning: Optional[str] = reasoning_field(
        interpretive=True, default=None, description="Required if hitl_type is set, otherwise null. "
    )
    hitl_description: Optional[str] = Field(
        default=None,
        description="Free-text elaboration of how the HITL pattern operates in the system, as reported."
    )
    hitl_type_other_specification: Optional[str] = Field(
        default=None,
        description="Free-text specification. Required if 'other' is in hitl_type, otherwise null."
    )
    domain_knowledge_formalization_present: bool = Field(
        description="True if domain knowledge is encoded in an explicit, reusable, machine-readable structure "
        "that the system uses. Free-text prompts, few-shot examples or unstructured RAG corpora alone do not count."
    )
    domain_knowledge_formalization_present_reasoning: str = reasoning_field(interpretive=True)
    domain_knowledge_type: Optional[UniqueList[DomainKnowledgeType]] = Field(
        default=None,
        description="All types of domain knowledge formalization present, required if domain_knowledge_formalization_present is true. "
        "Code every type that applies; a structure implementing another type (e.g., model code implementing an "
        "optimization model, an Asset Administration Shell serialised as XML) gets both (0.10.5)."
        + make_type_annotations(DomainKnowledgeType)
    )
    domain_knowledge_type_reasoning: Optional[str] = reasoning_field(
        interpretive=True, default=None, description="Required if domain_knowledge_type is set, otherwise null. "
    )
    domain_knowledge_description: Optional[str] = Field(
        default=None,
        description="Free-text elaboration of what domain knowledge is formalized and how, as reported."
    )
    domain_knowledge_type_other_specification: Optional[str] = Field(
        default=None,
        description="Free-text specification. Required if 'other' is in domain_knowledge_type, otherwise null."
    )
    evaluation_framework_used: bool = Field(
        description="True if the paper describes an explicit, repeatable evaluation protocol: defined test items "
        "or cases, defined metrics or scoring criteria, and a stated procedure. A single walkthrough, anecdotes, "
        "or metrics without a stated procedure do not count."
    )
    evaluation_framework_used_reasoning: str = reasoning_field(interpretive=True)
    evaluation_framework_type: Optional[UniqueList[EvaluationFrameworkType]] = Field(
        default=None,
        description="All framework elements used, required if evaluation_framework_used is true. Code both the "
        "test instrument (benchmark, custom test set, expert ground truth) and the scoring (rubric, "
        "domain-specific metric)."
        + make_type_annotations(EvaluationFrameworkType)
    )
    evaluation_framework_type_reasoning: Optional[str] = reasoning_field(
        interpretive=True, default=None, description="Required if evaluation_framework_type is set, otherwise null. "
    )
    evaluation_framework_description: Optional[str] = Field(
        default=None,
        description="Free-text elaboration of the evaluation framework and its application, as reported."
    )
    evaluation_framework_type_other_specification: Optional[str] = Field(
        default=None,
        description="Free-text specification. Required if 'other' is in evaluation_framework_type, otherwise null."
    )

    # B8: KG details; required iff ontology or knowledge-graph is in domain_knowledge_type.
    kg_model: Optional[KGModel] = Field(
        default=None,
        description="Graph data model; required iff domain_knowledge_type includes ontology or knowledge-graph, "
        "otherwise null." + make_type_annotations(KGModel)
    )
    kg_construction: Optional[KGConstruction] = Field(
        default=None,
        description="How the ontology/KG was built; required iff domain_knowledge_type includes ontology or "
        "knowledge-graph, otherwise null." + make_type_annotations(KGConstruction)
    )
    kg_usage: Optional[UniqueList[KGUsage]] = Field(
        default=None,
        description="All run-time uses of the ontology/KG; required iff domain_knowledge_type includes ontology or "
        "knowledge-graph, otherwise null." + make_type_annotations(KGUsage)
    )
    kg_reasoning: Optional[str] = reasoning_field(
        interpretive=True, default=None,
        description="Reasoning for kg_model, kg_construction and kg_usage; required iff they are set, otherwise null. "
    )
    standards_encoded: list[str] = Field(
        default_factory=list,
        description="Standards encoded machine-readably (e.g., 'VDI 5200', 'ISA-95', 'ISO 22400'); non-empty iff "
        "'standards-encoding' is in domain_knowledge_type."
    )
    automation_stage: UniqueList[AutomationStage] = Field(
        min_length=1,
        description="All information-processing stages the LLM system automates (Parasuraman et al. 2000). Stages refer "
        "to the planning decision the method supports and count when any component of the method performs them, incl. "
        "the solver or algorithm the LLM drives, not only the LLM. decision-selection and action-implementation refer "
        "to the final planning decision only: choices inside the search (an LLM tuning parameters or choosing "
        "heuristics/evaluation functions, parent or elitist selection, Pareto filtering) and decisions of agents inside "
        "a simulation are neither (0.10.4)."
        + make_type_annotations(AutomationStage)
    )
    automation_stage_reasoning: str = reasoning_field(interpretive=True)
    decision_autonomy: DecisionAutonomy = Field(
        description="Highest decision autonomy the system has over the real-world planning decision it supports; "
        "decisions made by agents inside a simulation do not count. '2-recommendation' requires the system to select or "
        "rank and present its preferred option; generating candidates for humans to evaluate and adjust is "
        "'1-options' (pilot 0.10.1)."
        + make_type_annotations(DecisionAutonomy)
    )
    decision_autonomy_reasoning: str = reasoning_field(interpretive=True)

    @model_validator(mode="after")
    def validate_conditional_types(self):
        """Type fields and their reasoning are required iff the corresponding flag is true; 'other' needs a specification."""
        for flag, type_field in (
            ("hitl_pattern_present", "hitl_type"),
            ("domain_knowledge_formalization_present", "domain_knowledge_type"),
            ("evaluation_framework_used", "evaluation_framework_type"),
        ):
            for field_name in (type_field, f"{type_field}_reasoning"):
                require_iff(self, field_name, getattr(self, flag), f"{flag} is true")
        require_spec_iff(self, "hitl_type", HITLType.OTHER, "hitl_type_other_specification")
        require_spec_iff(self, "domain_knowledge_type", DomainKnowledgeType.OTHER, "domain_knowledge_type_other_specification")
        require_spec_iff(self, "evaluation_framework_type", EvaluationFrameworkType.OTHER, "evaluation_framework_type_other_specification")
        knowledge = self.domain_knowledge_type or []
        has_kg = bool(KG_TYPES.intersection(knowledge))
        for field_name in ("kg_model", "kg_construction", "kg_usage", "kg_reasoning"):
            require_iff(self, field_name, has_kg, "domain_knowledge_type includes ontology or knowledge-graph")
        require_iff(self, "standards_encoded", DomainKnowledgeType.STANDARDS_ENCODING in knowledge,
                    "domain_knowledge_type includes standards-encoding")
        return self
